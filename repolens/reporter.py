from pathlib import Path

def header():
    print("============================================================")
    print("                          REPOLENS                          ")
    print("                Repository Analysis Tool v0.1               ")
    print("============================================================")
    print("\n")


def project_overview(project_statistics, path):
    print("[+] PROJECT OVERVIEW")
    print("------------------------------------------------------------")
    print(f"Project Name        :        {Path(path).name}")
    print(f"Project Path        :        {Path(path).resolve()}")
    print(f"Total Directories   :        {project_statistics['total_directories']}")
    print(f"Total Files         :        {project_statistics['total_files']}")
    print(f"Source Files        :        {project_statistics['source_files']}")
    print(f"Languages Detected  :        {len(project_statistics['languages'])}")
    print()

def language_distribution(project_statistics):
    print("[+] LANGUAGE DISTRIBUTION")
    print("------------------------------------------------------------")
    for language in project_statistics['languages']:
        print(f"{language}          :        {project_statistics['languages'][language]} file(s)")
    print()

def code_distribution(project_statistics):
    print("[+] CODE STATISTICS")
    print("------------------------------------------------------------")
    print(f"Total Lines         :        {project_statistics['total_lines']}")
    print(f"Code Lines          :        {project_statistics['code_lines']}")
    print(f"Comment Lines       :        {project_statistics['comment_lines']}")
    print(f"Blank Lines         :        {project_statistics['blank_lines']}")
    print(f"Comment Density     :        {round(project_statistics['comment_density'], 2)}%")
    print()

def long_line_analysis(project_statistics):
    print("[+] LONG LINE ANALYSIS")
    print("------------------------------------------------------------")
    print(f"Long Code Lines     :        {project_statistics['long_code_lines']}")
    print(f"Long Comment Lines  :        {project_statistics['long_comment_lines']}")
    print(f"Total Long Lines    :        {project_statistics['long_lines']}")
    print()

def readme_analysis(readme_analysis_data):
    print("[+] README ANALYSIS")
    print("------------------------------------------------------------")
    print(f"README Found        :        {'YES' if readme_analysis_data['found'] else 'NO'}")
    print(f"Status              :        {None if not readme_analysis_data['found'] else readme_analysis_data['empty']}")
    print(f"Total Lines:        :        {readme_analysis_data['total_lines']}")
    print(f"Blank Lines:        :        {readme_analysis_data['blank_lines']}")
    print(f"Total Words         :        {readme_analysis_data['total_words']}")
    print(f"Total Characters    :        {readme_analysis_data['total_chars']}")
    print()

def repository_rating(comment_score, long_line_score, readme_score, total_score, rating):
    print("[+] REPOSITORY RATING")
    print("------------------------------------------------------------")
    print(f"Comment Score       :        {comment_score} / 30")
    print(f"Long Line Score     :        {long_line_score} / 40")
    print(f"README Score        :        {readme_score} / 30")
    print("------------------------------------------------------------")
    print(f"Overall Score       :        {total_score} / 100")
    print(f"Rating              :        {rating}")
    print()

def analysis_summary(project_statistics, readme_analysis_data):
    print("[+] ANALYSIS SUMMARY")
    print("------------------------------------------------------------")
    print(f"- {len(project_statistics['languages'])} programming language(s) detected.")
    if readme_analysis_data['found']:
        print("- README documentation is available.")
    else:
        print("- README documentation is NOT available.")
    print(f"- {project_statistics['long_lines']} long line(s) detected.")
    print(f"- Comment Density: {round(project_statistics['comment_density'], 2)}%")
    print("\n")

def footer():
    print("============================================================")
    print("              Analysis completed successfully               ")
    print("                   Generated by RepoLens                    ")
    print("============================================================")

def report_everything(project_statistics, path, readme_analysis_data, comment_score, long_line_score, readme_score, total_score, rating):
    header()
    project_overview(project_statistics, path)
    language_distribution(project_statistics)
    code_distribution(project_statistics)
    long_line_analysis(project_statistics)
    readme_analysis(readme_analysis_data)
    repository_rating(comment_score, long_line_score, readme_score, total_score, rating)
    analysis_summary(project_statistics, readme_analysis_data)
    footer()